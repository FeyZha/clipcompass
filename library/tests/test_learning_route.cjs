const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(__dirname, "../static/learning-route.js"), "utf8"), context);
const group = (title, video, start, end) => ({title, question: title, clips: [{video_id: video, recommended_watch_start: start, recommended_watch_end: end}]});
const groups = [group("A", "v", 0, 10), group("B", "w", 0, 10), group("C", "v", 20, 30), group("bridge", "v", 8, 22)];
const before = JSON.stringify(groups);
const route = context.buildLearningRoute(groups);
assert.equal(route.length, 2);
assert.equal(route[0].video_id, "v");
assert.equal(route[0].recommended_watch_start, 0);
assert.equal(route[0].recommended_watch_end, 30);
assert.equal(route[0].titles.length, 3);
assert.equal(route[1].video_id, "w");
assert.equal(route.reduce((sum, row) => sum + row.recommended_watch_end - row.recommended_watch_start, 0), 40);
assert.equal(JSON.stringify(groups), before);
assert.equal(context.buildLearningRoute([]).length, 0);
assert.equal(context.buildLearningRoute([groups[0], groups[0]]).length, 1);
assert.equal(context.buildLearningRoute([groups[0], groups[2]]).length, 2);
console.log("Learning route: overlap, bridge, deduplication, duration, empty selection and immutability passed");
